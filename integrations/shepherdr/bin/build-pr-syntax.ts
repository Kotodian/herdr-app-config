// Rebuild the checked-in native highlighter after updating the pinned highlight.js dependency.
import { readFile } from 'node:fs/promises'

const root = new URL('../', import.meta.url)
const build = await Bun.build({
  entrypoints: [new URL('bin/pr-syntax-entry.js', root).pathname],
  target: 'browser', format: 'esm', minify: true,
})
if (!build.success) throw new Error(build.logs.join('\n'))
const license = await readFile(new URL('node_modules/highlight.js/LICENSE', root), 'utf8')
await Bun.write(new URL('core/pr-syntax-engine.js', root),
  `// Generated by bin/build-pr-syntax.ts. Do not edit.\n/*\n${license}*/\n${await build.outputs[0].text()}`)
